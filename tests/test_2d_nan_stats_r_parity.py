"""2D tracks with NaN cells read as R misha 5.12.1 reads them.

R adds a NaN cell to the statistics of any query that covers it: its area
counts, and the weighted sum and avg become NaN. min / max are C++'s std::min /
std::max along R's walk of the quad tree, which uses the statistics stored for
a node the query covers whole, so they depend on the order of that walk. The
tracks here are R's own files (a rects track and a points track, both split
into many chunks, and the points again written in parts), and the values R read
from them are frozen in tests/test_data/stats_2d_nan (regenerated by
tools/generate_2d_nan_stats_baseline.R), so no R is needed.

R reads avg, weighted.sum and area into floats, so those are compared at float
precision; min and max are compared exactly.
"""

import gzip
import hashlib
import json
import math
from pathlib import Path

import numpy as np
import pandas as pd
import pytest

import pymisha as pm
from pymisha import _quadtree
from pymisha.extract import _gextract_2d_vtrack_agg

FIXTURE = Path(__file__).parent / "test_data" / "stats_2d_nan"
BASELINE = json.loads((FIXTURE / "baseline.json").read_text())
QUERIES = pd.DataFrame(BASELINE["queries"])
GRID = pd.DataFrame(BASELINE["grid"])
FUNCS = {"avg": "avg", "min": "min", "max": "max", "weighted_sum": "weighted.sum", "area": "area"}
CASES = BASELINE["cases"]


def _case_id(case):
    return f"{case['track']}-{case['band_name']}"


def _band(case):
    return tuple(case["band"]) if case["band"] else None


def _r_rows(case):
    """R's gextract rows of a case: one per query that meets the band, by 1-based query index."""
    v = case["values"]
    ids = np.atleast_1d(v["intervalID"]).astype(int)
    out = {"intervalID": ids}
    for col in ["start1", "end1", "start2", "end2"]:
        out[col] = np.atleast_1d(v[col]).astype(int)
    for col in ["track", *FUNCS]:
        out[col] = np.array([float(x) for x in np.atleast_1d(v[col])])
    return pd.DataFrame(out)


def _assert_values(got, exp, col, where):
    """min / max exactly, the rest as the float R reads them into."""
    for g, e, qid in zip(got, exp, where, strict=True):
        if math.isnan(e):
            assert math.isnan(g), f"{col} of query {qid}: {g} where R gives NaN"
        elif col in ("min", "max"):
            assert g == e, f"{col} of query {qid}: {g} where R gives {e}"
        else:
            assert np.float32(g) == np.float32(e), f"{col} of query {qid}: {g} where R gives {e}"


def _mk_db(root, fmt):
    root.mkdir(parents=True)
    seqs = {"chrA": 4000, "chrB": 3000}
    if fmt == "indexed":
        fasta = root / "genome.fasta"
        fasta.write_text("".join(f">{c}\n{'A' * n}\n" for c, n in seqs.items()))
        fastas = [str(fasta)]
    else:
        fastas = []
        for c, n in seqs.items():
            (root / f"{c}.fasta").write_text(f">{c}\n{'A' * n}\n")
            fastas.append(str(root / f"{c}.fasta"))
    db = root / "db"
    pm.gdb_create(str(db), fastas, db_format=fmt)
    for gz in (FIXTURE / "tracks").rglob("*.gz"):
        out = db / gz.relative_to(FIXTURE).with_suffix("")
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_bytes(gzip.decompress(gz.read_bytes()))
    pm.gdb_init(str(db))
    if fmt == "indexed":
        for tr in ("rct", "pts", "pts_split"):
            pm.gtrack_2d_convert_to_indexed(tr, remove_old=True, force=False)
    return db


@pytest.fixture(scope="module")
def dbs(tmp_path_factory):
    base = tmp_path_factory.mktemp("stats_2d_nan")
    return {fmt: _mk_db(base / fmt, fmt) for fmt in ("per-chromosome", "indexed")}


@pytest.fixture(autouse=True)
def _no_progress(monkeypatch):
    monkeypatch.setitem(pm.CONFIG, "progress", False)
    yield
    pm.gvtrack_clear()


def test_baseline_is_r_5_12_1():
    assert BASELINE["misha"] == "5.12.1"


@pytest.mark.parametrize("fmt", ["per-chromosome", "indexed"])
@pytest.mark.parametrize("case", CASES, ids=_case_id)
def test_gextract_gives_r_values(dbs, case, fmt):
    """Each 2D virtual track function, and the track itself, over each query."""
    pm.gdb_init(str(dbs[fmt]))
    tr = case["track"]
    for k, f in FUNCS.items():
        pm.gvtrack_create(f"v_{k}", tr, f)
    rows = []
    for i in range(len(QUERIES)):
        q = QUERIES.iloc[[i]].reset_index(drop=True)
        r = pm.gextract([tr, *(f"v_{k}" for k in FUNCS)], q, iterator=q, band=_band(case),
                        colnames=["track", *FUNCS])
        if r is not None and len(r):
            rows.append(r.assign(intervalID=i + 1))
    got = pd.concat(rows, ignore_index=True)
    exp = _r_rows(case)
    pd.testing.assert_frame_equal(
        got[["intervalID", "start1", "end1", "start2", "end2"]].astype(int),
        exp[["intervalID", "start1", "end1", "start2", "end2"]].astype(int),
    )
    for col in ["track", *FUNCS]:
        _assert_values(got[col].to_numpy(dtype=float), exp[col].to_numpy(), col, exp["intervalID"])


@pytest.mark.parametrize("case", CASES, ids=_case_id)
def test_vtrack_agg_path_gives_r_values(dbs, case):
    """_gextract_2d_vtrack_agg, the path of a 2D vtrack the C++ scanner does not take."""
    pm.gdb_init(str(dbs["per-chromosome"]))
    exp = _r_rows(case)
    pos = exp["intervalID"].to_numpy() - 1
    for k, f in FUNCS.items():
        got = _gextract_2d_vtrack_agg(case["track"], "v", QUERIES, _band(case), f)["v"].to_numpy()
        _assert_values(got[pos], exp[k].to_numpy(), k, exp["intervalID"])


@pytest.mark.parametrize("case", CASES, ids=_case_id)
def test_python_reader_gives_r_values(dbs, case, monkeypatch):
    """The pure-Python quad-tree reader, as used without the C++ binding."""
    monkeypatch.setattr(_quadtree, "_HAS_CPP_QUADTREE", False)
    exp = _r_rows(case)
    track_dir = str(dbs["per-chromosome"] / "tracks" / f"{case['track']}.track")
    got = {k: np.full(len(QUERIES), np.nan) for k in ("weighted_sum", "min", "max")}
    got["area"] = np.zeros(len(QUERIES))
    for (c1, c2), idx in QUERIES.groupby(["chrom1", "chrom2"]).groups.items():
        pair = _quadtree.open_2d_pair(track_dir, c1, c2)
        if pair is None:
            continue
        is_points, num_objs, data, root, close = pair
        try:
            rects = QUERIES.loc[idx, ["start1", "start2", "end1", "end2"]].to_numpy(dtype=np.int64)
            s = _quadtree.query_2d_track_stats_batch(data, is_points, num_objs, root, rects, band=_band(case))
        finally:
            close()
        got["area"][idx] = s["occupied_area"]
        got["weighted_sum"][idx] = s["weighted_sum"]
        got["min"][idx] = s["min_val"]
        got["max"][idx] = s["max_val"]
    pos = exp["intervalID"].to_numpy() - 1
    for k in got:
        _assert_values(got[k][pos], exp[k].to_numpy(), k, exp["intervalID"])


@pytest.mark.parametrize("case", CASES, ids=_case_id)
def test_summaries_give_r_values(dbs, case):
    """gsummary, gquantiles, gdist and gscreen over a grid iterator, which take the avg of each cell.

    R summarizes the avgs as floats, pymisha as doubles: the tolerance allows for
    that, and a cell read wrongly moves these by far more.
    """
    pm.gdb_init(str(dbs["per-chromosome"]))
    tr, band, scope = case["track"], _band(case), pm.gintervals_2d_all()
    s = pm.gsummary(tr, scope, iterator=GRID, band=band)
    for k, v in case["summary"].items():
        np.testing.assert_allclose(float(s[k]), float(v), rtol=1e-6, atol=1e-5, err_msg=k)
    q = pm.gquantiles(tr, [0.1, 0.5, 0.9], scope, iterator=GRID, band=band)
    np.testing.assert_allclose(np.asarray(q, dtype=float).ravel(), [float(x) for x in case["quantiles"]],
                               rtol=1e-6, atol=1e-5)
    d = pm.gdist(tr, [-5, -2, 0, 2, 5], intervals=scope, iterator=GRID, band=band)
    assert np.asarray(d).tolist() == case["dist"]
    sc = pm.gscreen(f"{tr} > 0", scope, iterator=GRID, band=band)
    cols = ["chrom1", "start1", "end1", "chrom2", "start2", "end2"]
    exp = pd.DataFrame({c: np.atleast_1d(case["screen"].get(c, [])) for c in cols})
    got = pd.DataFrame(columns=cols) if sc is None else sc[cols]
    # the cells in the order R walks them
    assert _rows(got) == _rows(exp)


def _rows(df):
    return list(zip(df["chrom1"].astype(str), df["start1"].astype(int), df["end1"].astype(int),
                    df["chrom2"].astype(str), df["start2"].astype(int), df["end2"].astype(int), strict=True))


def test_gtrack_2d_create_writes_r_bytes(tmp_path):
    """gtrack_2d_create stores the node statistics R stores, NaN values included."""
    db = tmp_path / "db"
    fastas = []
    for c, n in {"chrA": 4000, "chrB": 3000}.items():
        (tmp_path / f"{c}.fasta").write_text(f">{c}\n{'A' * n}\n")
        fastas.append(str(tmp_path / f"{c}.fasta"))
    pm.gdb_create(str(db), fastas, db_format="per-chromosome")
    pm.gdb_init(str(db))
    rects = pd.read_csv(FIXTURE / "rct_input.tsv", sep="\t")
    assert rects["value"].isna().any()
    pm.gtrack_2d_create("rct1", "x", rects.drop(columns="value"), rects["value"].to_numpy())
    track_dir = db / "tracks" / "rct1.track"
    got = {p.name: (p.stat().st_size, hashlib.sha256(p.read_bytes()).hexdigest())
           for p in sorted(track_dir.iterdir()) if not p.name.startswith(".")}
    expected = {name: (f["size"], f["sha256"]) for name, f in BASELINE["rct1_files"].items()}
    assert got == expected
