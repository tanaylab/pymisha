@pytest.mark.parametrize("band", ["none", "band"])
def test_empty_query_area_is_zero(band):
    """A query that meets no cell has area 0 and NaN for the rest, as in R.

    That holds for a pair with a file and for one with none (chr2-chr2), and for
    a shifted vtrack that stays on the chromosome. A shift that takes the query
    off the chromosome is out of range: every function is NaN, area included.
    """
    case = BASELINE["empty_query"]
    q = _frame(case["queries"])
    funcs = {"avg": "avg", "min": "min", "max": "max", "weighted_sum": "weighted.sum", "area": "area"}
    for k, f in funcs.items():
        pm.gvtrack_create(f"v_{k}", "rects_track", f)
    pm.gvtrack_create("v_area_out", "rects_track", "area")
    pm.gvtrack_iterator_2d("v_area_out", sshift1=600000, eshift1=600000)
    pm.gvtrack_create("v_area_in", "rects_track", "area")
    pm.gvtrack_iterator_2d("v_area_in", sshift1=-5, eshift1=5)
    cols = case["cols"]
    got = pm.gextract(cols, q, iterator=q, band=(-5, 5) if band == "band" else None)
    exp = _frame(case[band])
    got = got.sort_values(COORDS).reset_index(drop=True)
    exp = exp.sort_values(COORDS).reset_index(drop=True)
    pd.testing.assert_frame_equal(got[COORDS].astype({c: int for c in COORDS[1:3] + COORDS[4:]}),
                                  exp[COORDS].astype({c: int for c in COORDS[1:3] + COORDS[4:]}),
                                  check_dtype=False)
    _assert_float_values(got, exp, cols)


@pytest.mark.parametrize("func", ["area", "avg"])
def test_empty_query_python_path(func):
    """The Python path of a 2D vtrack gives area 0 for a query that meets no cell, as R does."""
    from pymisha.extract import _gextract_2d_vtrack_agg

    case = BASELINE["empty_query"]
    q = _frame(case["queries"])
    exp = _frame(case["none"]).set_index(COORDS)
    got = _gextract_2d_vtrack_agg("rects_track", "v", q, None, func)
    exp_vals = exp.loc[[tuple(r) for r in q[COORDS].itertuples(index=False)], f"v_{func}"].to_numpy()
    _assert_float_values(pd.DataFrame({"v": got["v"]}), pd.DataFrame({"v": exp_vals}), ["v"])


