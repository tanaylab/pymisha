def _expected_contacts(files):
    """The contacts an import of these contacts files holds, by (chrom1, chrom2, x, y): each
    at its intervals' midpoints, ordered by chromosome (and in a cis pair x <= y), duplicates
    summed, a cis contact mirrored around the diagonal and a trans one in both files."""
    chrom_id = {c: i for i, c in enumerate(pm.gintervals_all()["chrom"])}
    sums: dict = {}
    for f in files:
        df = pd.read_csv(f, sep="\t", dtype={"chrom1": str, "chrom2": str})
        cols = ["chrom1", "start1", "end1", "chrom2", "start2", "end2", "value"]
        for c1, s1, e1, c2, s2, e2, v in df[cols].itertuples(index=False):
            x, y = (s1 + e1) // 2, (s2 + e2) // 2
            if (chrom_id[c1], x) > (chrom_id[c2], y):
                c1, c2, x, y = c2, c1, y, x
            sums[(c1, c2, x, y)] = sums.get((c1, c2, x, y), 0.0) + float(np.float32(v))
    out = {}
    for (c1, c2, x, y), v in sums.items():
        out[(c1, c2, x, y)] = out[(c2, c1, y, x)] = float(np.float32(v))
    return out


def _track_contacts(track):
    r = pm.gextract(track, pm.gintervals_2d_all())
    return {(c1, c2, int(x), int(y)): float(v)
            for c1, x, c2, y, v in r[["chrom1", "start1", "chrom2", "start2", track]].itertuples(index=False)}


@pytest.mark.parametrize("case,max_data_size", [("contacts", None), ("contacts_split", 16)])
def test_gtrack_2d_import_contacts_writes_r_bytes(case, max_data_size, _writer_track, monkeypatch):
    """gtrack_2d_import_contacts writes the files R writes: duplicates summed in R's
    order, a trans pair in both files, a pair in parts too (gmax.data.size)."""
    if max_data_size is not None:
        monkeypatch.setitem(pm.CONFIG, "max_data_size", max_data_size)
    _writer_track("test.w2d")
    inputs = [str(FIXTURE / "contacts_a.tsv"), str(FIXTURE / "contacts_b.tsv")]
    pm.gtrack_2d_import_contacts("test.w2d", "x", inputs)
    got, want = _track_contacts("test.w2d"), _expected_contacts(inputs)
    assert got.keys() == want.keys()
    np.testing.assert_allclose([got[k] for k in want], list(want.values()), rtol=1e-6)

    # R and pymisha insert the contacts in coordinate order, not the order of the hash
    # table that sums them, so the bytes are the same on every C++ library
    assert _track_files("test.w2d") == WRITERS[case]


# --- functions whose default scope is the 2D genome for a 2D expression -----------------------

DEFAULT = BASELINE["default_scope"]


def _close(got, exp, rtol=1e-6):
    """pymisha reads 2D values as doubles, R as floats: compared at float precision."""
    np.testing.assert_allclose(np.asarray(got, dtype=float), np.array([float(x) for x in np.atleast_1d(exp)]),
                               rtol=rtol, equal_nan=True)


@pytest.mark.parametrize("case", ["gcor", "gcor_spearman", "gcor_rect_band"])
def test_gcor_2d_as_r(case):
    """gcor of 2D expressions, by default over the 2D genome, as R computes it."""
    kwargs = {"gcor_spearman": {"method": "spearman.exact"},
              "gcor_rect_band": {"iterator": (100000, 100000), "band": (-200000, 0)}}.get(case, {})
    got = pm.gcor("rects_track", "rects_track * 2", details=True, **kwargs)
    for k, v in DEFAULT[case].items():
        _close([got[k].iloc[0]], [v])


def test_gbins_2d_default_scope_as_r():
    """gbins_summary and gbins_quantiles of a 2D expression read the 2D genome by default."""
    s = pm.gbins_summary("rects_track", [0, 10000, 70000], expr="rects_track")
    exp = DEFAULT["gbins_summary"]
    for j, k in enumerate(["Total intervals", "NaN intervals", "Min", "Max", "Sum", "Mean", "Std dev"]):
        _close(np.asarray(s)[:, j], exp[k])
    q = pm.gbins_quantiles("rects_track", [0, 10000, 70000], expr="rects_track", percentiles=[0.2, 0.5])
    _close(np.asarray(q).ravel(order="F"), DEFAULT["gbins_quantiles"])


def test_gsample_2d_default_scope():
    """gsample of a 2D expression samples the 2D genome's values by default: all of them
    when n exceeds their number, a subset of them otherwise."""
    expected = np.sort(np.array([float(x) for x in DEFAULT["gsample_all"]]))
    np.testing.assert_allclose(np.sort(pm.gsample("rects_track", 100000)), expected, rtol=1e-6)
    some = pm.gsample("rects_track", 5)
    assert len(some) == 5
    assert all(np.isclose(expected, v, rtol=1e-6).any() for v in some)


