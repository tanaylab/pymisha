# --- 2D iterators: the cells R walks, in its order, and their intervalID --------------------

WALK = BASELINE["walk"]


def _walk_inputs():
    return _frame(WALK["scope"]), _frame(WALK["iterator"])


def _assert_rows(got, exp, value_cols=()):
    """The rows R gives, in R's order: coordinates, intervalID and values."""
    assert got is not None, "pymisha gives no rows"
    got = got.reset_index(drop=True)
    assert len(got) == len(exp)
    if not LIBSTDCXX:
        keys = [c for c in (*COORDS, "intervalID") if c in exp]
        got = got.astype({"chrom1": str, "chrom2": str}).sort_values(keys, kind="stable").reset_index(drop=True)
        exp = exp.astype({"chrom1": str, "chrom2": str}).sort_values(keys, kind="stable").reset_index(drop=True)
    for c in COORDS:
        if c in ("chrom1", "chrom2"):
            assert got[c].astype(str).tolist() == exp[c].tolist(), c
        else:
            assert got[c].astype(np.int64).tolist() == exp[c].astype(np.int64).tolist(), c
    if "intervalID" in exp:
        assert got["intervalID"].astype(np.int64).tolist() == exp["intervalID"].astype(np.int64).tolist()
    _assert_float_values(got, exp, value_cols)


def _walk_iterator(kind, it):
    if kind in ("none", "none_band"):
        return None
    if kind.startswith("track"):
        return "rects_track"
    if kind.startswith("intervals"):
        return it
    if kind.startswith("rect"):
        return (70000, 90000)
    if kind == "cartesian":
        centers = pd.DataFrame(WALK["centers"]).astype({"chrom": str})
        return pm.giterator_cartesian_grid(centers, WALK["expansion"], stream=True)
    raise AssertionError(kind)


@pytest.mark.parametrize("kind", list(WALK["gextract"]))
def test_gextract_2d_walks_as_r(kind):
    """gextract over a 2D scope: R's cells, in R's order, with R's intervalID (scope row + 1).

    With no iterator R iterates the objects of the expression's 2D track, each cut by
    the scope intervals it meets (none, none_band); a band drops inter-chromosomal
    pairs and shrinks the cells to it.
    """
    scope, it = _walk_inputs()
    pm.gvtrack_create("v_area", "rects_track", "area")
    exprs = ["rects_track"] if kind.startswith("none") else ["rects_track", "v_area"]
    band = tuple(WALK["band"]) if kind.endswith("band") else None
    got = pm.gextract(exprs, scope, iterator=_walk_iterator(kind, it), band=band)
    _assert_rows(got, _frame(WALK["gextract"][kind]), exprs)


