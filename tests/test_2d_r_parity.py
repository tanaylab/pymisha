"""2D functions return what R misha 5.14.4 returns (with misha's sorted-contacts fix).

The values R returns on pymisha's own test database are frozen in
tests/test_data/2d_r_parity (regenerated by
tools/generate_2d_r_parity_baseline.R), so no R is needed. R reads avg, weighted.sum and area into floats, so those are compared at float
precision.
"""

import hashlib
import json
import math
import sys
from pathlib import Path

import numpy as np
import pandas as pd
import pytest

import _pymisha
import pymisha as pm

FIXTURE = Path(__file__).parent / "test_data" / "2d_r_parity"
BASELINE = json.loads((FIXTURE / "baseline.json").read_text())
COORDS = ["chrom1", "start1", "end1", "chrom2", "start2", "end2"]

# R's walk order and track bytes are those of R built on libstdc++: GIntervals2D::sort (and
# r_2d_sort_order, its port) uses std::sort, which is not stable, and libc++ (macOS) orders
# intervals with equal keys differently, in R too. There the same rows, and tracks of the
# same sizes and contents, are checked instead.
LIBSTDCXX = sys.platform != "darwin"


def _frame(d):
    """A frozen R result as a DataFrame, its values as floats."""
    df = pd.DataFrame({k: np.atleast_1d(v) for k, v in d.items()})
    for c in ("chrom1", "chrom2"):
        if c in df:
            df[c] = df[c].astype(str)
    for c in df.columns:
        if c not in COORDS and c != "intervalID":
            df[c] = [float(x) for x in df[c]]
    return df


def _assert_float_values(got, exp, cols):
    for col in cols:
        for i, (g, e) in enumerate(zip(got[col].to_numpy(dtype=float), exp[col].to_numpy(dtype=float), strict=True)):
            if math.isnan(e):
                assert math.isnan(g), f"{col}, row {i}: {g} where R gives NaN"
            else:
                assert np.float32(g) == np.float32(e), f"{col}, row {i}: {g} where R gives {e}"


