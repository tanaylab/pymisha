"""gtrack_liftover of a 2D track writes the bytes R misha 5.12.1's gtrack.liftover writes.

The source tracks, the chains and the size and SHA-256 of every file R wrote for
each case are frozen in tests/test_data/liftover_2d (regenerated by
tools/generate_liftover_2d_baseline.R), so no R is needed. The sources are R's
own files: the order in which a source is read follows its quad tree, and that
order decides first / last / nth.
"""

import gzip
import hashlib
import json
import shutil
from pathlib import Path

import pytest

import pymisha as pm

FIXTURE = Path(__file__).parent / "test_data" / "liftover_2d"
BASELINE = json.loads((FIXTURE / "baseline.json").read_text())


def _mk_db(root, fmt):
    """The target database of the baseline: chrT1 (8000bp) and chrT2 (6000bp)."""
    root.mkdir(parents=True)
    seqs = {"chrT1": 8000, "chrT2": 6000}
    if fmt == "indexed":
        fasta = root / "genome.fasta"
        fasta.write_text("".join(f">{c}\n{'A' * n}\n" for c, n in seqs.items()))
        fastas = [str(fasta)]
    else:
        fastas = []
        for c, n in seqs.items():
            (root / f"{c}.fasta").write_text(f">{c}\n{'A' * n}\n")
            fastas.append(str(root / f"{c}.fasta"))
    pm.gdb_create(str(root / "db"), fastas, db_format=fmt)
    return root / "db"


@pytest.fixture(scope="module")
def dbs(tmp_path_factory):
    """The R-written sources, ungzipped, and a target database per format."""
    base = tmp_path_factory.mktemp("liftover_2d_r_bytes")
    for fmt in ("per-chromosome", "indexed"):
        src = FIXTURE / f"src_{fmt}"
        dst = base / f"src_{fmt}"
        shutil.copytree(src, dst, ignore=shutil.ignore_patterns("*.gz"))
        for gz in src.rglob("*.gz"):
            out = dst / gz.relative_to(src).with_suffix("")
            out.write_bytes(gzip.decompress(gz.read_bytes()))
    tgt = {fmt: _mk_db(base / f"tgt_{fmt}", fmt) for fmt in ("per-chromosome", "indexed")}
    return base, tgt


def _files(track_dir):
    return {
        p.name: (p.stat().st_size, hashlib.sha256(p.read_bytes()).hexdigest())
        for p in sorted(track_dir.iterdir()) if not p.name.startswith(".")
    }


def test_baseline_is_r_5_12_1():
    assert BASELINE["misha"] == "5.12.1"


@pytest.mark.parametrize("case", BASELINE["cases"], ids=lambda c: c["name"])
def test_lifted_track_files_are_rs(dbs, case, monkeypatch):
    base, tgt = dbs
    pm.gdb_init(str(tgt[case["tgt"]]))
    monkeypatch.setitem(pm.CONFIG, "max_data_size", int(case["max_data_size"]))
    kwargs = {}
    if case["nth"] is not None:
        kwargs["params"] = int(case["nth"])
    if case["min_n"] is not None:
        kwargs["min_n"] = int(case["min_n"])
    pm.gtrack_liftover(
        case["name"], "x", str(base / f"src_{case['src']}" / "tracks" / f"{case['track']}.track"),
        str(FIXTURE / case["chain"]), src_overlap_policy="keep", tgt_overlap_policy=case["policy"],
        multi_target_agg=case["agg"], na_rm=case["na_rm"], **kwargs)
    got = _files(tgt[case["tgt"]] / "tracks" / f"{case['name']}.track")
    expected = {name: (f["size"], f["sha256"]) for name, f in case["files"].items()}
    assert got == expected
